import { Link } from 'react-router'
import { useProgress } from '../app/progress'
import { downloadProgress } from '../app/progressFiles'
import { useUI } from '../app/ui'
import { assetUrl } from '../config/assets'
import { project } from '../config/project'
import { HeroArt } from '../components/art/Art'
import { AssetImage } from '../components/AssetImage'
import { HeroLiveStack } from '../components/home/HeroLiveStack'
import { Icon, type IconName } from '../components/Icon'
import { Medal } from '../components/Medal'
import { useDocumentTitle } from '../components/PageHeader'
import { ColoredCode } from '../components/RichText'
import { ACHIEVEMENTS } from '../learning/achievements'
import { CHALLENGE_COUNT } from '../learning/challenges'
import { CONCEPTS, LESSON_ORDER } from '../learning/concepts'
import { LESSONS } from '../learning/lessons'
import { conceptLevels, totalScore } from '../learning/progress'
import './Home.css'

const FEATURES: Array<{ title: string; text: string; to: string; icon: IconName; color: string; cta: string }> = [
  { title: 'Learn', text: 'Eight short lessons, each with a hands-on widget and a quick check.', to: '/learn', icon: 'book', color: 'curly', cta: 'Start the course' },
  { title: 'Visualize', text: 'Step through the algorithm like a debugger: editor, Stack, flowchart and pseudocode in sync.', to: '/visualizer', icon: 'layers', color: 'square', cta: 'Open the Visualizer' },
  { title: 'Experiment', text: 'Paste real code, break the algorithm on purpose and measure its complexity.', to: '/playground', icon: 'flask', color: 'round', cta: 'Open the Playground' },
  { title: 'Quiz', text: 'Ten mixed questions per run, with explanations and a weak-concept report.', to: '/quiz', icon: 'quiz', color: 'curly', cta: 'Take the quiz' },
  { title: 'Compare', text: 'Run Stack, Counter and Queue side by side and see exactly where they disagree.', to: '/compare', icon: 'columns', color: 'brand', cta: 'Compare them' },
  { title: 'Challenge', text: 'Five levels from `()` to real C code. Predict, locate the bug, earn stars.', to: '/challenges', icon: 'trophy', color: 'round', cta: 'Take a challenge' },
]

export default function HomePage() {
  useDocumentTitle('')
  const { progress } = useProgress()
  const ui = useUI()
  const lessonsDone = LESSON_ORDER.filter((id) => progress.lessons[id]?.completed).length
  const challengesDone = Object.values(progress.challenges).filter((c) => c.completed).length
  const levels = conceptLevels(progress)
  const mastered = CONCEPTS.filter((c) => levels[c.id] === 'mastered').length
  const score = totalScore(progress)
  const accuracy = progress.quiz.totalAnswered ? Math.round((progress.quiz.totalCorrect / progress.quiz.totalAnswered) * 100) : null
  const nextLesson = LESSONS.find((l) => !progress.lessons[l.id]?.completed)
  const unlocked = ACHIEVEMENTS.filter((a) => progress.achievements[a.id]).length

  return (
    <div className="home">
      {/* ---------------- hero ---------------- */}
      <section className="hero" aria-labelledby="hero-title">
        <div className="hero__inner">
          <div className="hero__text">
            <span className="eyebrow">
              <Icon name="layers" /> {project.subject} · Stack case study
            </span>
            <h1 id="hero-title" className="hero__title">
              Watch a <span className="hero__accent">Stack</span> Think
            </h1>
            <p className="hero__sub">
              Learn how Stack data structures solve balanced-bracket problems through interactive visualization, prediction, experimentation, and
              challenges.
            </p>
            <div className="hero__ctas">
              <Link to="/learn" className="btn btn--primary btn--lg">
                <Icon name="book" /> Start Learning
              </Link>
              <Link to="/visualizer" className="btn btn--lg">
                <Icon name="layers" /> Open Visualizer
              </Link>
              <Link to="/challenges" className="btn btn--lg btn--ghost">
                <Icon name="trophy" /> Take a Challenge
              </Link>
            </div>
            <p className="hero__note small muted">
              Built around the case study report “{project.reportTitle}”. Every animation is generated by a real Stack running the report's algorithm.
            </p>
          </div>
          <div className="hero__visual">
            <div className="hero__art">
              <AssetImage slot="hero" alt={assetUrl('hero') ? 'Project illustration' : ''} fallback={<HeroArt />} eager />
            </div>
            <div className="hero__live">
              <HeroLiveStack />
            </div>
          </div>
        </div>
      </section>

      <div className="page home__body">
        {/* ---------------- continue + progress ---------------- */}
        <section className="home__progress" aria-labelledby="progress-title">
          <div className="card continue">
            <h2 className="card__title">
              <Icon name="arrowRight" /> Continue where you left off
            </h2>
            {progress.lastVisited ? (
              <>
                <p className="continue__where">{progress.lastVisited.label}</p>
                <p className="small muted">Last visited {new Date(progress.lastVisited.at).toLocaleString()}</p>
                <div className="row">
                  <Link className="btn btn--primary" to={progress.lastVisited.path}>
                    Continue <Icon name="arrowRight" />
                  </Link>
                  {nextLesson && (
                    <Link className="btn" to={`/learn/${nextLesson.id}`}>
                      Next lesson: {nextLesson.number}. {nextLesson.title}
                    </Link>
                  )}
                </div>
              </>
            ) : (
              <>
                <p className="continue__where">Lesson 1: What is a Stack?</p>
                <p className="small muted">Four minutes, one working Stack to play with, one quick question.</p>
                <div className="row">
                  <Link className="btn btn--primary" to="/learn/what-is-a-stack">
                    Begin Lesson 1 <Icon name="arrowRight" />
                  </Link>
                  <button type="button" className="btn" onClick={ui.openIntro}>
                    Why do we need a Stack?
                  </button>
                </div>
              </>
            )}
          </div>

          <div className="card yourprogress">
            <h2 id="progress-title" className="card__title">
              <Icon name="chart" /> Your Progress
            </h2>
            <dl className="ptiles">
              <div className="ptile ptile--curly">
                <dt>Lessons completed</dt>
                <dd>
                  {lessonsDone} / {LESSONS.length}
                </dd>
              </div>
              <div className="ptile ptile--brand">
                <dt>Quiz best score</dt>
                <dd>{progress.quiz.runs ? `${progress.quiz.bestScore} / ${progress.quiz.bestTotal}` : '—'}</dd>
                <span className="ptile__sub">{accuracy !== null ? `${accuracy}% accuracy overall` : 'No quiz yet'}</span>
              </div>
              <div className="ptile ptile--round">
                <dt>Challenges</dt>
                <dd>
                  {challengesDone} / {CHALLENGE_COUNT}
                </dd>
              </div>
              <div className="ptile ptile--square">
                <dt>Streak</dt>
                <dd>
                  <Icon name="flame" /> {progress.streak.current} day{progress.streak.current === 1 ? '' : 's'}
                </dd>
                <span className="ptile__sub">Best {progress.streak.best}</span>
              </div>
              <div className="ptile">
                <dt>Score</dt>
                <dd>{score.total.toLocaleString()} pts</dd>
                <span className="ptile__sub">
                  lessons {score.lessons} · quiz {score.quiz} · challenges {score.challenges}
                </span>
              </div>
              <div className="ptile">
                <dt>Predictions</dt>
                <dd>
                  {progress.predictions.correct} / {progress.predictions.total}
                </dd>
                <span className="ptile__sub">correct</span>
              </div>
            </dl>

            <div className="concepts">
              <div className="concepts__head">
                <h3 className="concepts__title">Concept checklist</h3>
                <span className="small muted">
                  {mastered} of {CONCEPTS.length} mastered
                </span>
              </div>
              <div
                className="pbar"
                role="progressbar"
                aria-label="Concepts mastered"
                aria-valuemin={0}
                aria-valuemax={CONCEPTS.length}
                aria-valuenow={mastered}
              >
                <div className="pbar__fill" style={{ width: `${(mastered / CONCEPTS.length) * 100}%` }} />
              </div>
              <ul className="concepts__list">
                {CONCEPTS.map((c) => {
                  const lvl = levels[c.id]
                  return (
                    <li key={c.id} className={`concept concept--${lvl}`}>
                      <Icon name={lvl === 'mastered' ? 'checkCircle' : lvl === 'learning' ? 'clock' : 'target'} />
                      <Link to={`/learn/${c.lesson}`}>{c.label}</Link>
                      <span className="concept__lvl">{lvl === 'mastered' ? 'Mastered' : lvl === 'learning' ? 'Learning' : 'Not started'}</span>
                    </li>
                  )
                })}
              </ul>
            </div>
            <div className="row small">
              <button type="button" className="btn btn--sm btn--ghost" onClick={() => downloadProgress(progress)}>
                <Icon name="download" /> Export progress
              </button>
              <button type="button" className="btn btn--sm btn--ghost" onClick={ui.openHelp}>
                <Icon name="upload" /> Import (in Help)
              </button>
            </div>
          </div>
        </section>

        {/* ---------------- features ---------------- */}
        <section aria-labelledby="features-title" className="home__section">
          <h2 id="features-title" className="home__h2">
            Six ways to understand one algorithm
          </h2>
          <div className="features">
            {FEATURES.map((f) => (
              <Link key={f.title} to={f.to} className={`feature feature--${f.color}`}>
                <span className="feature__icon">
                  <Icon name={f.icon} />
                </span>
                <span className="feature__title">{f.title}</span>
                <span className="feature__text">
                  {f.text.split('`').map((part, i) => (i % 2 ? <ColoredCode key={i} text={part} /> : part))}
                </span>
                <span className="feature__cta">
                  {f.cta} <Icon name="arrowRight" />
                </span>
              </Link>
            ))}
          </div>
        </section>

        {/* ---------------- achievements ---------------- */}
        <section aria-labelledby="ach-title" className="home__section">
          <div className="home__sechead">
            <h2 id="ach-title" className="home__h2">
              Achievements
            </h2>
            <span className="badge badge--brand">
              {unlocked} / {ACHIEVEMENTS.length} unlocked
            </span>
          </div>
          <ul className="achievements">
            {ACHIEVEMENTS.map((a) => {
              const at = progress.achievements[a.id]
              return (
                <li key={a.id} className={`achievement ${at ? 'is-unlocked' : 'is-locked'}`}>
                  <Medal achievement={a} locked={!at} />
                  <span className="achievement__text">
                    <strong>{a.title}</strong>
                    <span className="small muted">{a.how}</span>
                    <span className={`badge ${at ? 'badge--success' : ''}`}>
                      <Icon name={at ? 'check' : 'lock'} /> {at ? `Unlocked ${new Date(at).toLocaleDateString()}` : 'Locked'}
                    </span>
                  </span>
                </li>
              )
            })}
          </ul>
        </section>

        {/* ---------------- about ---------------- */}
        <section aria-labelledby="about-title" className="home__section about">
          <div className="about__text">
            <span className="eyebrow">
              <Icon name="file" /> About this project
            </span>
            <h2 id="about-title" className="home__h2">
              {project.reportTitle}
            </h2>
            <h3>Problem statement</h3>
            <p>
              Given a string containing the characters <ColoredCode text="( ) [ ] { }" />, determine whether the sequence of brackets is balanced: every
              opening bracket has a matching closing bracket of the same type, brackets close in the correct order (the most recently opened first), and no
              closing bracket appears without a corresponding opening bracket.
            </p>
            <h3>Objective</h3>
            <p>
              Explain how modern code editors instantly flag mismatched brackets, and show why the Stack is the natural data structure for validating
              nested symbols in source code.
            </p>
            <h3>Approach</h3>
            <p>
              Scan the input once. Push every opening bracket; for every closing bracket, check that the top of the Stack is its partner and pop it. The
              input is balanced only if the Stack is empty at the end. The same logic drives bracket highlighting, red error underlines, auto-indentation
              and code folding in editors such as VS Code and IntelliJ IDEA.
            </p>
            <h3>Complexity</h3>
            <ul>
              <li>
                <strong>Time O(n)</strong>: each of the n characters is processed exactly once; push and pop are O(1).
              </li>
              <li>
                <strong>Space O(n) worst case</strong> (every character an opening bracket), <strong>O(1) best case</strong> (no brackets). In general
                O(k), k = the most unmatched opening brackets stored at once.
              </li>
            </ul>
          </div>
          <aside className="about__side">
            <div className="card reportcard">
              <span className="reportcard__kind">{project.reportKind}</span>
              <strong className="reportcard__title">{project.reportTitle}</strong>
              <dl className="reportcard__meta">
                <div>
                  <dt>Submitted by</dt>
                  <dd>
                    <ul>
                      {project.students.map((s) => (
                        <li key={s}>{s}</li>
                      ))}
                    </ul>
                  </dd>
                </div>
                {project.guide && (
                  <div>
                    <dt>Guide</dt>
                    <dd>{project.guide}</dd>
                  </div>
                )}
                <div>
                  <dt>Department</dt>
                  <dd>{project.department}</dd>
                </div>
                {project.college && (
                  <div>
                    <dt>College</dt>
                    <dd>
                      {project.college}
                      {project.location ? `, ${project.location}` : ''}
                    </dd>
                  </div>
                )}
                {project.academicYear && (
                  <div>
                    <dt>Academic year</dt>
                    <dd>{project.academicYear}</dd>
                  </div>
                )}
              </dl>
              <a className="btn btn--soft" href={`${import.meta.env.BASE_URL}${project.reportFile}`} target="_blank" rel="noreferrer">
                <Icon name="file" /> Read the report (PDF)
              </a>
            </div>
            <figure className="about__figure">
              {assetUrl('about') ? (
                <AssetImage slot="about" alt="Project team or report" fallback={<HeroArt />} className="about__img" />
              ) : (
                <AssetImage
                  slot="report-stack-evolution"
                  alt="Figure 1 from the report: the stack after each step while scanning {[()]}"
                  fallback={<HeroArt />}
                  className="about__img"
                />
              )}
              <figcaption className="small muted">
                {assetUrl('about') ? project.reportTitle : 'Original diagram from the project report (Figure 1): stack evolution while scanning {[()]}.'}
              </figcaption>
            </figure>
          </aside>
        </section>
      </div>
    </div>
  )
}

